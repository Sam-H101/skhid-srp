"""Writes the generated 0.26g tables of crates/survarium/src/v026g/:

    item_params/table.rs    one row per item of items_dict, from the item's own
                           config (gameplay/items/**.options)
    maps/table.rs          one row per maps_dict id that has a config
                           (gameplay/game_modes/*.options)

Input: a directory holding the files of 0.26g's resources.db whose path
contains "gameplay/", as tools/re-kit/common/dbgrab writes them ('/' -> '__'):

    dbgrab <resources.db> get gameplay/ <dir>
    dbgrab <resources.db> list > <list.txt>
    python -I gen_data.py <dir> <srp-026g>/crates/survarium/src/v026g <list.txt>

Nothing here is chosen by srp: every value is read from the game's files.
"""
import os
import struct
import sys

# `python -I` leaves the script's own directory off the path.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bincfg  # noqa: E402

source, target = sys.argv[1], sys.argv[2]


def load(path):
    """A config by its resources.db path, or None when the db has no such file."""
    file = os.path.join(source, path.replace("/", "__"))
    return bincfg.load(file) if os.path.exists(file) else None


def rows(table):
    return table if isinstance(table, list) else list(table.values())


def f32(value):
    """The shortest literal that reads back as the same f32."""
    value = float(value)
    bits = struct.pack("<f", value)
    for digits in range(1, 10):
        text = "%.*g" % (digits, value)
        if struct.pack("<f", float(text)) == bits:
            break
    if "e" in text or "." not in text:
        text = repr(float(text))
        if "e" in text:
            text = "%f" % float(text)
    return text


def rust_str(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def boolean(value):
    return "true" if value else "false"


dictionary = load("gameplay/db_static_dictionaries")

# --- item parameters -------------------------------------------------------

lines = []
for item in sorted(rows(dictionary["items_dict"]), key=lambda item: item["dict_id"]):
    config = load(item["cfg_name"])
    if config is None:
        raise SystemExit("no config for %s" % item["name"])
    p = config.get("parameters", {})
    rarity = p.get("rarity", [])
    if rarity and isinstance(rarity[0], list):
        gear_rarity, stack_rarity = [], [(int(low), int(high)) for low, high in rarity]
    else:
        gear_rarity, stack_rarity = [int(level) for level in rarity], []
    fields = [
        ("dict_id", str(item["dict_id"])),
        ("kind", rust_str(p.get("type", ""))),
        ("faction", str(int(p.get("faction", 0)))),
        ("faction_affinity", str(int(p.get("faction_affinity", 0)))),
        ("item_level", str(int(p.get("item_level", 0)))),
        ("match_making_level", str(int(p.get("match_making_level", 0)))),
        ("base_rarity_level", str(int(p.get("base_rarity_level", 0)))),
        ("gear_rarity", "&[%s]" % ", ".join(map(str, gear_rarity))),
        ("stack_rarity", "&[%s]" % ", ".join("(%d, %d)" % pair for pair in stack_rarity)),
        ("weight", f32(p.get("weight", 0))),
        ("drop_weight", str(int(p.get("drop_weight", 0)))),
        ("degrade_per_use", f32(p.get("degrade_per_use", 0))),
        ("degrade_per_match", f32(p.get("degrade_per_match", 0))),
        ("degrade_per_death", f32(p.get("degrade_per_death", 0))),
        ("reliability", f32(p.get("reliability", 0))),
        ("repair_cost_ratio", f32(p.get("repair_cost_ratio", 0))),
        ("clip_size", str(int(p.get("clip_size", 0)))),
        ("clip_weight", f32(p.get("clip_weight", 0))),
        ("required_bags", str(int(p.get("required_bags", 0)))),
        ("magazine_capacity", str(int(p.get("magazine_capacity", 0)))),
        ("double_handed", boolean(p.get("double_handed", False))),
        ("fills_whole_pocket", boolean(p.get("fills_whole_pocket", False))),
        ("modification", str(int(p.get("modification", 0)))),
        (
            "default_modifications",
            "&[%s]" % ", ".join(str(int(m)) for m in config.get("default_modifications", [])),
        ),
    ]
    lines.append(
        "    ItemParams { %s }, // %s"
        % (", ".join("%s: %s" % field for field in fields), item["name"])
    )

player = load("gameplay/players/default.player")["player"]
stamina = player["stamina_params"]

with open(os.path.join(target, "item_params", "table.rs"), "w", newline="\n") as out:
    out.write(
        "// Generated by scripts/gen-data-026g/gen_data.py from 0.26g's resources.db\n"
        "// (gameplay/items/**.options, gameplay/players/default.player). Do not edit.\n\n"
        "use super::ItemParams;\n\n"
        "/// `gameplay/players/default.player`: `player.stamina_params.max_carried_weight`.\n"
        "pub const MAX_CARRIED_WEIGHT: f32 = %s;\n"
        "/// `player.stamina_params.min_carried_weight`.\n"
        "pub const MIN_CARRIED_WEIGHT: f32 = %s;\n"
        "/// `player.ammo_bags_count`.\n"
        "pub const AMMO_BAGS_COUNT: u32 = %d;\n"
        "/// `player.pocket_slots_count`.\n"
        "pub const POCKET_SLOTS_COUNT: u32 = %d;\n"
        "/// `player.pocket_slot_size`.\n"
        "pub const POCKET_SLOT_SIZE: u32 = %d;\n\n"
        "/// By `dict_id`.\n"
        "#[rustfmt::skip]\n"
        "pub const ITEM_PARAMS: &[ItemParams] = &[\n%s\n];\n"
        % (
            f32(stamina["max_carried_weight"]),
            f32(stamina["min_carried_weight"]),
            player["ammo_bags_count"],
            player["pocket_slots_count"],
            player["pocket_slot_size"],
            "\n".join(lines),
        )
    )

# --- maps and modes ---------------------------------------------------------

lines = []
for entry in sorted(rows(dictionary["maps_dict"]), key=lambda entry: entry["id"]):
    config = load("gameplay/game_modes/" + entry["cfg_mode_name"])
    if config is None:
        continue  # ids 114 and 143..151: maps_dict names a file the db lacks
    mode = config["mode"]
    p = mode.get("parameters", {})
    making = mode.get("match_making_params", {})
    ui = mode.get("ui", {})
    project = making.get("map_name", "")
    fields = [
        ("id", str(entry["id"])),
        ("config", rust_str(entry["cfg_mode_name"])),
        ("name", rust_str(mode.get("name", ""))),
        ("mode", str(int(mode.get("mode", 0)))),
        ("level", str(int(making.get("map_id", 0)))),
        ("weather", str(int(making.get("map_weather_id", 0)))),
        ("project", rust_str(project)),
        # Whether resources.db has projects/<project>/client_project (set below).
        ("has_project", None),
        ("loading_screen_id", str(int(ui.get("loading_screen_id", 0)))),
        ("icon", str(int(ui.get("icon", 0)))),
        ("rules", "&[%s]" % ", ".join(str(int(rule)) for rule in mode.get("rules", []))),
        ("match_time", str(int(p.get("match_time", 0)))),
        ("wait_time", str(int(p.get("wait_time", 0)))),
        ("countdown_time", str(int(p.get("countdown_time", 0)))),
        ("wait_player_percent", f32(p.get("wait_player_percent", 0))),
        ("respawn_time", str(int(p.get("respawn_time", 0)))),
        ("victory_items_count", str(int(p.get("victory_items_count", 0)))),
        ("vi_spawn_time", str(int(p.get("vi_spawn_time", 0)))),
        ("vi_spawn_variation", str(int(p.get("vi_spawn_variation", 0)))),
        ("spawn_points_count", str(int(p.get("spawn_points_count", 0)))),
        ("tickets_count", str(int(p.get("tickets_count", 0)))),
    ]
    lines.append((entry["id"], project, fields))

# The projects resources.db ships, from its file list (one path a line), if
# given: `has_project` is then read from it; without it every level_0X
# project but level_08/night_* is taken as present (modes_maps.md §2).
projects = None
if len(sys.argv) > 3:
    with open(sys.argv[3], encoding="utf-8", errors="replace") as listing:
        projects = {
            line.split("\t")[0].strip()[len("projects/"):-len("/client_project")]
            for line in listing
            if line.startswith("projects/") and line.split("\t")[0].strip().endswith("/client_project")
        }

rendered = []
for map_id, project, fields in lines:
    if projects is not None:
        present = project in projects
    else:
        present = project.startswith("level_0") and "/night_" not in project
    text = ", ".join(
        "%s: %s" % (name, boolean(present) if name == "has_project" else value)
        for name, value in fields
    )
    rendered.append("    MapMode { %s }," % text)

with open(os.path.join(target, "maps", "table.rs"), "w", newline="\n") as out:
    out.write(
        "// Generated by scripts/gen-data-026g/gen_data.py from 0.26g's resources.db\n"
        "// (maps_dict of gameplay/db_static_dictionaries, gameplay/game_modes/*.options,\n"
        "// and the projects/*/client_project list). Do not edit.\n\n"
        "use super::MapMode;\n\n"
        "/// Every `maps_dict` id whose config the client ships, by id.\n"
        "#[rustfmt::skip]\n"
        "pub const MAP_MODES: &[MapMode] = &[\n%s\n];\n" % "\n".join(rendered)
    )
print("items", len(rows(dictionary["items_dict"])), "maps", len(rendered))
