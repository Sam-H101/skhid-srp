"""Writes crates/survarium/src/v026g/modifications/table.rs: what each item of
0.26g's items_dict may be modified with, from the item's own config
(gameplay/items/**.options):

    available_modifications_mask   a string of '0'/'1'; character j stands for
                                   the modifications whose `type_mask`
                                   (gameplay/items/modifications/
                                   modifications.options) has character j + 1
                                   set (that file's masks have one more
                                   character in front)
    available_defects_mask         the same for the defects
    camo_available, decal_available

Input as gen_data.py's: the directory of 0.26g's gameplay/ files ('/' -> '__').

    python -I gen_modifications.py <dir> <srp-026g>/crates/survarium/src/v026g

Nothing here is chosen by srp: every value is read from the game's files.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bincfg  # noqa: E402

source, target = sys.argv[1], sys.argv[2]


def load(path):
    file = os.path.join(source, path.replace("/", "__"))
    return bincfg.load(file) if os.path.exists(file) else None


def rows(table):
    return table if isinstance(table, list) else list(table.values())


def bits(mask):
    """The mask as a number: character j is bit j + 1."""
    return sum(1 << (j + 1) for j, char in enumerate(mask) if char == "1")


dictionary = load("gameplay/db_static_dictionaries")
lines = []
for item in sorted(rows(dictionary["items_dict"]), key=lambda item: item["dict_id"]):
    config = load(item["cfg_name"])
    if config is None:
        raise SystemExit("no config for %s" % item["name"])
    p = config.get("parameters", {})
    modifications = bits(p.get("available_modifications_mask", ""))
    defects = bits(p.get("available_defects_mask", ""))
    camo, decal = bool(p.get("camo_available", False)), bool(p.get("decal_available", False))
    if not (modifications or defects or camo or decal):
        continue
    lines.append(
        "    ItemMods { dict_id: %d, modifications: 0x%X, defects: 0x%X, camo: %s, decal: %s }, // %s"
        % (
            item["dict_id"],
            modifications,
            defects,
            "true" if camo else "false",
            "true" if decal else "false",
            item["name"],
        )
    )

with open(os.path.join(target, "modifications", "table.rs"), "w", newline="\n") as out:
    out.write(
        "// Generated by scripts/gen-data-026g/gen_modifications.py from 0.26g's\n"
        "// resources.db (gameplay/items/**.options). Do not edit.\n\n"
        "use super::ItemMods;\n\n"
        "/// By `dict_id`; an item with nothing set is left out.\n"
        "#[rustfmt::skip]\n"
        "pub const ITEM_MODS: &[ItemMods] = &[\n%s\n];\n" % "\n".join(lines)
    )
print("%d items" % len(lines))
